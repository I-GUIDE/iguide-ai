def chat_memory_mapping() -> Dict[str, Any]:
    """The fields as nested properties: leaf -> type name, object -> {"properties": {...}}."""
    root: Dict[str, Any] = {}
    for path, kind in CHAT_MEMORY_FIELDS.items():
        *parents, leaf = path.split(".")
        node = root
        for part in parents:
            node = node.setdefault(part, {"properties": {}})["properties"]
        node[leaf] = {"properties": {}} if kind == "object" else kind
    return root
